<?php

namespace App\Enums;

enum ContentSource: string
{
    case Manual = 'manual';
    case Ai = 'ai';
    case WooCommerce = 'woocommerce';
    case Sample = 'sample';

    public function label(): string
    {
        return match ($this) {
            self::Manual => 'Written manually',
            self::Ai => 'AI generated',
            self::WooCommerce => 'Imported from WooCommerce',
            self::Sample => 'Sample AI Output (not generated by Gemini)',
        };
    }

    /**
     * Whether a person wrote or approved this content, so it may be sent to a store.
     */
    public function isApprovedForSync(): bool
    {
        return $this === self::Manual || $this === self::Ai || $this === self::Sample;
    }
}
